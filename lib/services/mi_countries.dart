// ISO 3166-1 alpha-2 names for the myinstants country filter.
// Arabic is the t() key (English lives in i18n.dart). [en] is also stored
// so the picker can match a typed query in either language.
import '../i18n.dart';

class MiCountry {
  final String code;
  final String ar;
  final String en;
  const MiCountry(this.code, this.ar, this.en);

  /// Regional-indicator flag. Missing glyphs fall back to the platform font.
  String get flag {
    final units = code.toUpperCase().codeUnits;
    return String.fromCharCodes(
        [units[0] + 0x1F1E6 - 0x41, units[1] + 0x1F1E6 - 0x41]);
  }

  String get label => t(ar);
}

